"""
Agent 7: Doc Generator Agent

Reads from state:  file_manifest, symbol_tables, dependency_graph,
                   graph_stats, circular_deps, circular_nodes,
                   complexity_scores, topological_order, explanations,
                   owner, repo_name, default_branch
Writes to state:   final_doc

Pure synthesis. No LLM calls. No network. No file I/O.
Each section is built by an independent function wrapped in try/except.
One section failing never prevents the rest from rendering.
"""

from datetime import datetime
from pathlib import PurePosixPath

from src.state import ArchaeonState

# Section configuration
ARCH_MAP_CAP      = 15   # files in the architecture map
READING_ORDER_CAP = 25   # files in the reading order list
TECH_DEBT_FN_CAP  = 10   # functions in the complex-functions table
MAX_RELATED       = 6    # dependents/dependencies shown per component
COMPONENT_CAP     = 40   # max components written to the document


def run(state: ArchaeonState) -> ArchaeonState:
    print(f"\n[Agent 7: Doc Generator]")

    builders = [
        ("Header",           _build_header),
        ("Project Summary",  _build_project_summary),
        ("Statistics",       _build_stats_section),
        ("Architecture Map", _build_architecture_map),
        ("Core Components",  _build_core_components),
        ("Tech Debt Report", _build_tech_debt_report),
        ("Reading Order",    _build_reading_order),
        ("Footer",           _build_footer),
    ]

    sections = []
    for name, builder in builders:
        try:
            content = builder(state)
            if content and content.strip():
                sections.append(content)
                print(f"  ✓  {name}")
            else:
                print(f"  –  {name} (empty, skipped)")
        except Exception as exc:
            # Log the failure but continue building the rest of the document.
            # A missing Architecture Map is better than no document at all.
            print(f"  ✗  {name} (error: {exc})")

    state.final_doc = '\n\n---\n\n'.join(sections)

    word_count = len(state.final_doc.split())
    line_count = state.final_doc.count('\n') + 1
    print(f"\n  Document: {line_count} lines · {word_count} words · "
          f"{len(sections)} sections")
    print(f"\n[Agent 7: Doc Generator] Done")
    return state


