def _repo_name(state: ArchaeonState) -> str:
    if state.repo_name:
        return state.repo_name
    try:
        parts = state.repo_url.rstrip("/").split("/")
        return parts[-1] if parts else "unknown-repo"
    except Exception:
        return "unknown-repo"


def _repo_owner(state: ArchaeonState) -> str:
    if state.owner:
        return state.owner
    try:
        parts = state.repo_url.rstrip("/").split("/")
        return parts[-2] if len(parts) >= 2 else "unknown"
    except Exception:
        return "unknown"


def _default_branch(state: ArchaeonState) -> str:
    return state.default_branch or "main"


def _language_breakdown(state: ArchaeonState) -> dict:
    """
    Count files per language from file_manifest.
    file_manifest contains FileMetadata objects — access .language directly.
    """
    counts: dict = {}
    for f in state.file_manifest:
        lang = f.language if hasattr(f, "language") else f.get("language", "Unknown")
        counts[lang] = counts.get(lang, 0) + 1
    return dict(sorted(counts.items(), key=lambda x: x[1], reverse=True))


def _risk_counts(state: ArchaeonState) -> dict:
    counts = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    for cs in state.complexity_scores.values():
        level = getattr(cs, "risk_level", "LOW")
        if level in counts:
            counts[level] += 1
    return counts


def _in_degree_map(state: ArchaeonState) -> dict:
    if state.dependency_graph is None:
        return {}
    return dict(state.dependency_graph.in_degree())


def _out_degree_map(state: ArchaeonState) -> dict:
    if state.dependency_graph is None:
        return {}
    return dict(state.dependency_graph.out_degree())


def _short_path(path: str, max_parts: int = 3) -> str:
    parts = path.replace("\\", "/").split("/")
    return "/".join(parts[-max_parts:]) if len(parts) > max_parts else path


def _timestamp() -> str:
    return datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")


def _total_functions(state: ArchaeonState) -> int:
    total = 0
    for st in state.symbol_tables.values():
        fns = st.functions if hasattr(st, "functions") else st.get("functions", [])
        total += len(fns)
    return total


def _total_classes(state: ArchaeonState) -> int:
    total = 0
    for st in state.symbol_tables.values():
        cls = st.classes if hasattr(st, "classes") else st.get("classes", [])
        total += len(cls)
    return total


def _get_fn_name(fn) -> str:
    return fn.name if hasattr(fn, "name") else fn.get("name", "?")


def _get_fn_complexity(fn) -> float:
    return (fn.complexity if hasattr(fn, "complexity") else fn.get("complexity", 0)) or 0


def _get_classes(st) -> list:
    return st.classes if hasattr(st, "classes") else st.get("classes", [])


def _get_class_name(cls) -> str:
    return cls.name if hasattr(cls, "name") else cls.get("name", "?")


def _get_class_methods(cls) -> list:
    return cls.methods if hasattr(cls, "methods") else cls.get("methods", [])


