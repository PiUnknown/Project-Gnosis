# Section 6: Tech Debt Report
# -----------------------------------------------------------------------

def _build_tech_debt_report(state: ArchaeonState) -> str:
    lines = ["## Tech Debt Report\n"]
    any_debt = False

    # ---- Circular dependencies ------------------------------------------
    if state.circular_deps:
        any_debt = True
        lines.append(
            f"### Circular Dependencies\n\n"
            f"⚠️ **{len(state.circular_deps)} cycle(s) detected.** "
            f"These files cannot be read in isolation — each depends on "
            f"something that depends on it. Refactor before touching.\n"
        )
        for cycle in state.circular_deps[:8]:
            names    = [PurePosixPath(p).name for p in cycle]
            cycle_str = " → ".join(names) + f" → {names[0]}"
            lines.append(f"- `{cycle_str}`")
        if len(state.circular_deps) > 8:
            lines.append(f"- *...and {len(state.circular_deps) - 8} more cycles*")
        lines.append("")
    else:
        lines.append(
            "### Circular Dependencies\n\n"
            "✅ No circular dependencies detected.\n"
        )

    # ---- Critical risk files --------------------------------------------
    critical_scores = [
        s for s in state.complexity_scores.values()
        if s.risk_level == "CRITICAL"
    ]
    if critical_scores:
        any_debt = True
        lines.append("### Critical Risk Files\n")
        lines.append("| File | Reasons |")
        lines.append("|---|---|")
        for score in sorted(critical_scores, key=lambda s: -s.max_complexity):
            name    = PurePosixPath(score.file_path).name
            reasons = "; ".join(score.risk_reasons[:2]) or "see complexity report"
            lines.append(f"| `{name}` | {reasons} |")
        lines.append("")

    # ---- Most complex functions -----------------------------------------
    all_fns = []
    for score in state.complexity_scores.values():
        for fn_name, complexity in score.function_scores.items():
            if complexity >= 6:   # only worth flagging
                all_fns.append((complexity, fn_name, score.file_path))

    if all_fns:
        any_debt = True
        all_fns.sort(key=lambda x: -x[0])
        top_fns = all_fns[:TECH_DEBT_FN_CAP]
        lines.append("### Most Complex Functions\n")
        lines.append("Functions with cyclomatic complexity ≥ 6 "
                     "(hard to test and modify safely).\n")
        lines.append("| Complexity | Function | File |")
        lines.append("|:---:|---|---|")
        for complexity, fn_name, file_path in top_fns:
            fname = PurePosixPath(file_path).name
            lines.append(f"| {int(complexity)} | `{fn_name}` | `{fname}` |")
        lines.append("")

    # ---- High coupling files --------------------------------------------
    high_coupling = [
        s for s in state.complexity_scores.values()
        if s.coupling_score >= 6
    ]
    if high_coupling:
        any_debt = True
        high_coupling.sort(key=lambda s: -s.coupling_score)
        lines.append("### High Coupling Files\n")
        lines.append(
            "These files import from many internal modules. "
            "Changing any of their dependencies may affect them.\n"
        )
        lines.append("| File | Internal Imports | Risk |")
        lines.append("|---|:---:|---|")
        for score in high_coupling[:8]:
            name = PurePosixPath(score.file_path).name
            lines.append(
                f"| `{name}` | {score.coupling_score} | {score.risk_level} |"
            )
        lines.append("")

    # ---- Parse failures -------------------------------------------------
    parse_failures = [
        s for s in state.complexity_scores.values()
        if s.parse_error
    ]
    if parse_failures:
        any_debt = True
        lines.append("### Files with Parse Errors\n")
        lines.append(
            "These files contain syntax errors. tree-sitter could not "
            "fully parse them. They were not chunked into the RAG collection "
            "and may produce incorrect analysis results.\n"
        )
        for score in parse_failures[:8]:
            lines.append(f"- `{score.file_path}`")
        if len(parse_failures) > 8:
            lines.append(f"- *...and {len(parse_failures) - 8} more*")
        lines.append("")

    if not any_debt:
        lines.append(
            "*No significant tech debt signals detected. "
            "Run a more detailed audit on files rated MEDIUM risk "
            "or above in the complexity report.*"
        )

    return '\n'.join(lines)


