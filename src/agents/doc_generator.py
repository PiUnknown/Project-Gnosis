def _build_footer(state: ArchaeonState) -> str:
    now      = datetime.now().strftime("%Y-%m-%d %H:%M")
    n_agents = 7
    scores   = list(state.complexity_scores.values())
    risk_dist = _compute_risk_distribution(state)

    risk_summary = " · ".join(
        f"{level}: {risk_dist.get(level, 0)}"
        for level in ("CRITICAL", "HIGH", "MEDIUM", "LOW")
    )

    return (
        f"## About This Document\n\n"
        f"Generated by **Project Gnosis** — Code Archaeology Agent  \n"
        f"Generated at: `{now}`  \n"
        f"Pipeline: {n_agents} agents ran in sequence  \n"
        f"Files analyzed: {len(state.file_manifest)}  \n"
        f"Files scored: {len(scores)}  \n"
        f"Risk distribution: {risk_summary}  \n"
        f"Files explained: {len(state.explanations)}  \n\n"
        f"*This document is a snapshot. Re-run Project Gnosis after "
        f"significant changes to keep it current.*  \n\n"
        f"> **Outputs:** `onboarding.md` · `complexity_report.json` · "
        f"`dependency_graph.html` · `symbol_tables.json` · "
        f"`graph_data.json` · `explanations.json`"
    )


# -----------------------------------------------------------------------
# Shared utilities
# -----------------------------------------------------------------------

def _compute_language_breakdown(state: ArchaeonState) -> dict:
    counts: dict = {}
    for f in state.file_manifest:
        if f.language not in ("Markdown", "YAML", "TOML", "Unknown"):
            counts[f.language] = counts.get(f.language, 0) + 1
    return counts


def _compute_risk_distribution(state: ArchaeonState) -> dict:
    dist: dict = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    for score in state.complexity_scores.values():
        dist[score.risk_level] = dist.get(score.risk_level, 0) + 1
    return dist