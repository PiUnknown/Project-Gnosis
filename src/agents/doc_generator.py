# Section 3: Repository Statistics
# -----------------------------------------------------------------------

def _build_stats_section(state: ArchaeonState) -> str:
    lang_breakdown = _compute_language_breakdown(state)
    total_lang     = sum(lang_breakdown.values()) or 1
    lang_str = ', '.join(
        f"{lang} ({count / total_lang * 100:.0f}%)"
        for lang, count in sorted(lang_breakdown.items(), key=lambda x: -x[1])
    ) if lang_breakdown else "—"

    total_files   = len(state.file_manifest)
    total_funcs   = sum(len(st.functions) for st in state.symbol_tables.values())
    total_classes = sum(len(st.classes)   for st in state.symbol_tables.values())
    explained     = len(state.explanations)

    risk_dist = _compute_risk_distribution(state)
    risky     = risk_dist.get("CRITICAL", 0) + risk_dist.get("HIGH", 0)

    G = state.dependency_graph
    edges = G.number_of_edges() if G else 0

    rows = [
        ("Files analyzed",        str(total_files)),
        ("Languages",             lang_str),
        ("Functions extracted",   str(total_funcs)),
        ("Classes extracted",     str(total_classes)),
        ("Import relationships",  str(edges)),
        ("Files explained",       f"{explained} of {len(state.complexity_scores)}"),
        ("High-risk files",       str(risky)),
        ("Circular dependencies", str(len(state.circular_deps))),
    ]

    table = "| Metric | Value |\n|---|---|\n"
    for metric, value in rows:
        table += f"| {metric} | {value} |\n"

    return f"## Repository Statistics\n\n{table}"


