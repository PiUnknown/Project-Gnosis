# Complexity report serialiser
# ═══════════════════════════════════════════════════════════════════════════

def generate_complexity_report_json(state: ArchaeonState) -> str:
    """
    Serialise complexity_scores to a JSON string for state.complexity_report_json.
    Uses actual ComplexityScore field names: parse_error, is_in_circular_dep.
    """
    report = {}
    for fp, cs in state.complexity_scores.items():
        report[fp] = {
            "risk_level": getattr(cs, "risk_level", "UNKNOWN"),
            "avg_complexity": getattr(cs, "avg_complexity", 0.0),
            "max_complexity": getattr(cs, "max_complexity", 0.0),
            "max_complexity_function": getattr(cs, "max_complexity_function", None),
            "coupling_score": getattr(cs, "coupling_score", 0),
            "parse_error": getattr(cs, "parse_error", False),
            "is_in_circular_dep": getattr(cs, "is_in_circular_dep", False),
            "risk_reasons": getattr(cs, "risk_reasons", []),
        }
    return json.dumps(report, indent=2)


