def _build_header(state: ArchaeonState) -> str:
    repo = _repo_name(state)
    branch = _default_branch(state)
    return (
        f"# {repo} — Architecture Overview\n\n"
        f"**Generated by Project Gnosis (Code Archaeology Agent)**  \n"
        f"**Repository:** {state.repo_url}  \n"
        f"**Branch:** {branch}  \n"
        f"**Generated:** {_timestamp()}  \n"
        f"**Analysis Mode:** {state.analysis_mode}\n\n"
        f"---\n\n"
    )


def _build_project_summary(state: ArchaeonState) -> str:
    lang_breakdown = _language_breakdown(state)
    risk = _risk_counts(state)

    lang_str = ", ".join(
        f"{lang} ({count} files)"
        for lang, count in list(lang_breakdown.items())[:5]
    )

    return (
        f"## Project Summary\n\n"
        f"**{_repo_name(state)}** contains **{state.files_analyzed}** analyzed files "
        f"({state.files_discovered} discovered).\n\n"
        f"**Languages:** {lang_str or 'Unknown'}  \n"
        f"**Total functions extracted:** {_total_functions(state)}  \n"
        f"**Risk distribution:** {risk['CRITICAL']} CRITICAL · {risk['HIGH']} HIGH · "
        f"{risk['MEDIUM']} MEDIUM · {risk['LOW']} LOW\n\n"
    )


def _build_repository_statistics(state: ArchaeonState) -> str:
    lang_breakdown = _language_breakdown(state)
    risk = _risk_counts(state)

    g = state.dependency_graph
    graph_nodes = g.number_of_nodes() if g else 0
    graph_edges = g.number_of_edges() if g else 0

    top_lang = list(lang_breakdown.keys())[0] if lang_breakdown else "Unknown"
    top_lang_pct = (
        round(lang_breakdown[top_lang] / max(state.files_analyzed, 1) * 100)
        if lang_breakdown else 0
    )

    rows = [
        ("Files discovered", state.files_discovered),
        ("Files analyzed", state.files_analyzed),
        ("Analysis mode", state.analysis_mode),
        ("Primary language", f"{top_lang} ({top_lang_pct}%)"),
        ("Total functions", _total_functions(state)),
        ("Total classes", _total_classes(state)),
        ("Dependency graph nodes", graph_nodes),
        ("Dependency graph edges", graph_edges),
        ("Circular dependencies", len(state.circular_deps)),
        ("CRITICAL risk files", risk["CRITICAL"]),
        ("HIGH risk files", risk["HIGH"]),
    ]

    table = "| Metric | Value |\n|--------|-------|\n"
    table += "\n".join(f"| {k} | {v} |" for k, v in rows)
    return f"## Repository Statistics\n\n{table}\n\n"


def _build_architecture_map(state: ArchaeonState) -> str:
    if state.dependency_graph is None:
        return "## Architecture Map\n\n*Dependency graph not available.*\n\n"

    in_deg = dict(state.dependency_graph.in_degree())
    if not in_deg:
        return "## Architecture Map\n\n*No dependency data.*\n\n"

    top = sorted(in_deg.items(), key=lambda x: x[1], reverse=True)[:15]

    lines = [
        "## Architecture Map",
        "",
        "Top files by dependency in-degree (how many other files import each one):",
        "",
        "| File Path | In-Degree (Imports) | Risk Level |",
        "| :--- | :---: | :---: |",
    ]
    for path, deg in top:
        short = _short_path(path)
        cs = state.complexity_scores.get(path)
        risk = getattr(cs, "risk_level", "LOW")
        lines.append(f"| `{short}` | {deg} | **{risk}** |")
    lines.append("")
    return "\n".join(lines) + "\n"


def _build_core_components(state: ArchaeonState) -> str:
    if state.dependency_graph is None:
        return "## Core Components\n\n*Dependency graph not available.*\n\n"

    in_deg = dict(state.dependency_graph.in_degree())
    top = sorted(in_deg.items(), key=lambda x: x[1], reverse=True)
    top = [(fp, d) for fp, d in top if d > 0][:20]

    lines = ["## Core Components", ""]

    for fp, deg in top:
        short = _short_path(fp)
        cs = state.complexity_scores.get(fp)
        risk = getattr(cs, "risk_level", "?") if cs else "?"
        avg_cc = getattr(cs, "avg_complexity", 0.0) if cs else 0.0

        preds = list(state.dependency_graph.predecessors(fp))
        succs = list(state.dependency_graph.successors(fp))

        lines.append(f"### `{short}`")
        lines.append(f"**Risk:** {risk} · **In-degree:** {deg} · **Avg CC:** {avg_cc:.1f}")
        if succs:
            lines.append(f"**Depends on:** {', '.join(_short_path(s) for s in succs[:6])}")
        if preds:
            lines.append(f"**Depended on by:** {', '.join(_short_path(p) for p in preds[:6])}")

        explanation = state.explanations.get(fp)
        if explanation:
            lines.append("")
            lines.append(explanation.strip())

        lines.append("")

    return "\n".join(lines) + "\n"


def _build_tech_debt_report(state: ArchaeonState) -> str:
    lines = ["## Tech Debt Report", ""]

    # Circular dependencies
    if state.circular_deps:
        lines += ["### Circular Dependencies", ""]
        lines.append("| Cycle # | Dependencies Cycle | Length |")
        lines.append("| :---: | :--- | :---: |")
        for i, cycle in enumerate(state.circular_deps[:10], 1):
            cycle_str = " → ".join(f"`{_short_path(f)}`" for f in cycle) + f" → `{_short_path(cycle[0])}`"
            lines.append(f"| {i} | {cycle_str} | {len(cycle)} |")
        lines.append("")
    else:
        lines += ["### Circular Dependencies", "", "No circular dependencies detected.", ""]

    # CRITICAL files
    critical = [
        (fp, cs) for fp, cs in state.complexity_scores.items()
        if getattr(cs, "risk_level", "") == "CRITICAL"
    ]
    if critical:
        lines += ["### CRITICAL Risk Files", ""]
        lines.append("| File | Max CC | Avg CC | Coupling | Notes |")
        lines.append("|------|--------|--------|----------|-------|")
        for fp, cs in sorted(
            critical, key=lambda x: getattr(x[1], "max_complexity", 0), reverse=True
        )[:15]:
            short = _short_path(fp)
            max_cc = getattr(cs, "max_complexity", 0)
            avg_cc = getattr(cs, "avg_complexity", 0.0)
            coupling = getattr(cs, "coupling_score", 0)
            notes = []
            if getattr(cs, "parse_error", False):        # actual field name
                notes.append("parse error")
            if getattr(cs, "is_in_circular_dep", False): # actual field name
                notes.append("in cycle")
            if max_cc >= 21:
                notes.append(f"CC={max_cc:.0f}")
            lines.append(
                f"| `{short}` | {max_cc:.0f} | {avg_cc:.1f} | {coupling} | "
                f"{', '.join(notes) or '—'} |"
            )
        lines.append("")

    # Parse errors — uses score.parse_error (actual field name)
    parse_errors = [
        fp for fp, cs in state.complexity_scores.items()
        if getattr(cs, "parse_error", False)
    ]
    if parse_errors:
        lines += ["### Parse Errors", ""]
        lines.append("| ID | File Path | Status |")
        lines.append("| :---: | :--- | :---: |")
        for i, fp in enumerate(parse_errors[:10], 1):
            lines.append(f"| {i} | `{_short_path(fp)}` | ⚠️ PARSE ERROR |")
        lines.append("")

    # High complexity functions — uses score.function_scores dict (actual field)
    high_cc_funcs = []
    for fp, cs in state.complexity_scores.items():
        fn_scores = getattr(cs, "function_scores", {}) or {}
        for fn_name, complexity in fn_scores.items():
            if (complexity or 0) >= 10:
                high_cc_funcs.append((fp, fn_name, complexity))
    high_cc_funcs.sort(key=lambda x: x[2], reverse=True)

    lines += ["### High Complexity Functions", ""]
    if high_cc_funcs:
        lines.append("| File | Function | Cyclomatic Complexity |")
        lines.append("|------|----------|-----------------------|")
        for fp, fn_name, cc in high_cc_funcs[:20]:
            lines.append(f"| `{_short_path(fp)}` | `{fn_name}` | {cc} |")
    else:
        lines.append("No functions with cyclomatic complexity ≥ 10 detected.")
    lines.append("")

    return "\n".join(lines) + "\n"


def _build_reading_order(state: ArchaeonState) -> str:
    lines = ["## Suggested Reading Order", ""]

    if state.circular_deps:
        lines.append(
            "⚠️ **Circular dependencies detected.** "
            "A strict topological order does not exist. The list below is approximate."
        )
        lines.append("")

    order = state.topological_order or []
    if order:
        lines.append("| Order | File Path | Risk Level |")
        lines.append("| :---: | :--- | :---: |")
        for i, fp in enumerate(order[:25], 1):
            short = _short_path(fp)
            cs = state.complexity_scores.get(fp)
            risk = getattr(cs, "risk_level", "LOW")
            lines.append(f"| {i} | `{short}` | **{risk}** |")
        if len(order) > 25:
            lines.append(f"\n*...and {len(order) - 25} more files.*")
    else:
        lines.append("*Reading order not available.*")

    lines.append("")
    return "\n".join(lines) + "\n"


