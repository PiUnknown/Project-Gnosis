def _build_header(state: ArchaeonState) -> str:
    date_str = datetime.now().strftime("%B %d, %Y")
    repo_url = f"https://github.com/{state.owner}/{state.repo_name}"
    return (
        f"# {state.repo_name} — Architecture Overview\n\n"
        f"> **Generated by Project Gnosis** · {date_str}  \n"
        f"> Repository: [{state.owner}/{state.repo_name}]({repo_url})  \n"
        f"> Branch: `{state.default_branch or 'main'}`"
    )


