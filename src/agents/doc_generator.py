def _ac_architectural_relationships(state: ArchaeonState) -> str:
    lines = ["## Architectural Relationships", ""]

    if state.dependency_graph is None:
        lines += ["*Dependency graph not available.*", ""]
        return "\n".join(lines) + "\n"

    in_deg = dict(state.dependency_graph.in_degree())
    top = [
        (fp, d)
        for fp, d in sorted(in_deg.items(), key=lambda x: x[1], reverse=True)
        if d > 0
    ][:6]

    if not top:
        lines += ["*No significant dependency chains found.*", ""]
        return "\n".join(lines) + "\n"

    lines.append("Direct relationships for the most-imported modules:")
    lines.append("")

    for fp, deg in top:
        short = _short_path(fp)
        preds = list(state.dependency_graph.predecessors(fp))
        succs = list(state.dependency_graph.successors(fp))
        lines.append(f"**`{short}`** — imported by {deg} file(s)")
        if succs:
            lines.append(
                f"  - Imports: {', '.join(f'`{_short_path(s)}`' for s in succs[:6])}"
            )
        if preds:
            overflow = f" *(+{len(preds)-6} more)*" if len(preds) > 6 else ""
            lines.append(
                f"  - Imported by: {', '.join(f'`{_short_path(p)}`' for p in preds[:6])}"
                + overflow
            )
        lines.append("")

    return "\n".join(lines) + "\n"


def _ac_high_risk_areas(state: ArchaeonState) -> str:
    lines = ["## High Risk Areas", ""]

    if not state.complexity_scores:
        lines += ["*Complexity scores not available.*", ""]
        return "\n".join(lines) + "\n"

    risky = [
        (fp, cs) for fp, cs in state.complexity_scores.items()
        if getattr(cs, "risk_level", "") in ("CRITICAL", "HIGH")
    ]

    if not risky:
        lines += ["No CRITICAL or HIGH risk files detected.", ""]
        return "\n".join(lines) + "\n"

    lines.append("**Do not modify without understanding the full dependency surface.**")
    lines.append("")
    lines.append("| File | Risk | Max CC | Coupling | In-degree |")
    lines.append("|------|------|--------|----------|-----------|")

    in_deg = _in_degree_map(state)
    risky.sort(key=lambda x: (
        0 if getattr(x[1], "risk_level", "") == "CRITICAL" else 1,
        -getattr(x[1], "max_complexity", 0),
    ))

    for fp, cs in risky[:15]:
        short = _short_path(fp)
        risk = getattr(cs, "risk_level", "?")
        max_cc = getattr(cs, "max_complexity", 0)
        coupling = getattr(cs, "coupling_score", 0)
        deg = in_deg.get(fp, 0)
        lines.append(f"| `{short}` | {risk} | {max_cc:.0f} | {coupling} | {deg} |")

    lines.append("")
    return "\n".join(lines) + "\n"


def _ac_circular_dependencies(state: ArchaeonState) -> str:
    lines = ["## Circular Dependencies", ""]

    if not state.circular_deps:
        lines += ["No circular dependencies detected.", ""]
        return "\n".join(lines) + "\n"

    n = len(state.circular_deps)
    lines.append(
        f"**{n} cycle(s) detected.** "
        "All files in cycles are marked CRITICAL risk. "
        "Resolve cycles before refactoring any member file."
    )
    lines.append("")

    for cycle in state.circular_deps[:10]:
        chain = " → ".join(f"`{_short_path(f)}`" for f in cycle)
        chain += f" → `{_short_path(cycle[0])}`"
        lines.append(f"- {chain}")

    if n > 10:
        lines.append(f"\n*...and {n - 10} more cycles.*")

    lines.append("")
    return "\n".join(lines) + "\n"


def _ac_important_domain_objects(state: ArchaeonState) -> str:
    lines = ["## Important Domain Objects", ""]

    if not state.symbol_tables:
        lines += ["*Symbol tables not available.*", ""]
        return "\n".join(lines) + "\n"

    in_deg = _in_degree_map(state)
    all_classes = []

    for fp, st in state.symbol_tables.items():
        for cls in _get_classes(st):
            cls_name = _get_class_name(cls)
            method_count = len(_get_class_methods(cls))
            all_classes.append((in_deg.get(fp, 0), fp, cls_name, method_count))

    all_classes.sort(key=lambda x: x[0], reverse=True)

    if not all_classes:
        lines += ["*No class definitions found.*", ""]
        return "\n".join(lines) + "\n"

    lines.append("Classes ranked by the import importance of their containing file:")
    lines.append("")

    for deg, fp, cls_name, method_count in all_classes[:15]:
        short = _short_path(fp)
        dep_note = f" · file imported by {deg} module(s)" if deg > 0 else ""
        lines.append(f"- **`{cls_name}`** in `{short}` — {method_count} method(s){dep_note}")

    lines.append("")
    return "\n".join(lines) + "\n"


def _ac_change_impact_guide(state: ArchaeonState) -> str:
    lines = ["## Change Impact Guide", ""]

    if state.dependency_graph is None:
        lines += ["*Dependency graph not available.*", ""]
        return "\n".join(lines) + "\n"

    in_deg = dict(state.dependency_graph.in_degree())
    top = [
        (fp, d)
        for fp, d in sorted(in_deg.items(), key=lambda x: x[1], reverse=True)
        if d > 0
    ][:8]

    if not top:
        lines += ["*No dependency data to derive impact from.*", ""]
        return "\n".join(lines) + "\n"

    lines.append("When modifying a file below, verify all direct dependents still behave correctly.")
    lines.append("")

    for fp, deg in top:
        short = _short_path(fp)
        preds = list(state.dependency_graph.predecessors(fp))
        cs = state.complexity_scores.get(fp)
        risk = getattr(cs, "risk_level", "?") if cs else "?"

        lines.append(f"**If modifying `{short}` ({risk} risk · {deg} direct dependent(s)):**")
        for p in preds[:7]:
            lines.append(f"  - `{_short_path(p)}`")
        if len(preds) > 7:
            lines.append(f"  - *...and {len(preds) - 7} more*")
        lines.append("")

    return "\n".join(lines) + "\n"


def _ac_safe_starting_points(state: ArchaeonState) -> str:
    lines = ["## Safe Starting Points", ""]

    if not state.complexity_scores:
        lines += ["*Complexity scores not available.*", ""]
        return "\n".join(lines) + "\n"

    in_deg = _in_degree_map(state)
    out_deg = _out_degree_map(state)

    low_risk = [
        (fp, cs) for fp, cs in state.complexity_scores.items()
        if getattr(cs, "risk_level", "") == "LOW"
        and not getattr(cs, "parse_error", False)   # actual field name
    ]
    low_risk.sort(key=lambda x: (in_deg.get(x[0], 0), out_deg.get(x[0], 0)))

    if not low_risk:
        lines += ["*No LOW risk files identified.*", ""]
        return "\n".join(lines) + "\n"

    lines.append("Low complexity, low coupling. Read and modify these first.")
    lines.append("")

    for fp, cs in low_risk[:10]:
        short = _short_path(fp)
        avg_cc = getattr(cs, "avg_complexity", 0.0)
        coupling = getattr(cs, "coupling_score", 0)
        deg = in_deg.get(fp, 0)
        lines.append(
            f"- `{short}` — avg CC: {avg_cc:.1f} · coupling: {coupling} · "
            f"imported by: {deg} module(s)"
        )

    lines.append("")
    return "\n".join(lines) + "\n"


def _ac_ai_explanations(state: ArchaeonState) -> str:
    lines = ["## AI Explanations", ""]

    if not state.explanations:
        lines.append(
            "*LLM-generated architectural explanations were not included in this analysis.*"
        )
        lines.append("")
        return "\n".join(lines) + "\n"

    in_deg = _in_degree_map(state)
    sorted_exps = sorted(
        state.explanations.items(),
        key=lambda x: in_deg.get(x[0], 0),
        reverse=True,
    )

    for fp, explanation in sorted_exps[:15]:
        short = _short_path(fp)
        cs = state.complexity_scores.get(fp)
        risk_tag = f" · {getattr(cs, 'risk_level', '?')} risk" if cs else ""
        deg = in_deg.get(fp, 0)
        lines.append(f"### `{short}`{risk_tag} · in-degree: {deg}")
        lines.append("")
        lines.append(explanation.strip())
        lines.append("")

    return "\n".join(lines) + "\n"


