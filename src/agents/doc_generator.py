# Section 2: Project Summary
# -----------------------------------------------------------------------

def _build_project_summary(state: ArchaeonState) -> str:
    lines = ["## Project Summary\n"]

    # Opening: first two sentences of the most-imported explained file.
    # This gives the document a grounding statement about what the repo does,
    # sourced from the LLM explanation of the file most central to the codebase.
    opening = _get_summary_opening(state)
    if opening:
        lines.append(opening + "\n")

    # Language and size context
    lang_breakdown = _compute_language_breakdown(state)
    total = sum(lang_breakdown.values()) or 1
    lang_parts = [
        f"{lang} ({count / total * 100:.0f}%)"
        for lang, count in sorted(lang_breakdown.items(), key=lambda x: -x[1])[:4]
    ]
    lang_str = ", ".join(lang_parts) if lang_parts else "unknown"

    total_files   = len(state.file_manifest)
    total_funcs   = sum(len(st.functions) for st in state.symbol_tables.values())
    total_classes = sum(len(st.classes)   for st in state.symbol_tables.values())
    explained     = len(state.explanations)

    summary = (
        f"This repository contains **{total_files} analyzed files** "
        f"in {lang_str}. "
        f"**{total_funcs} functions** and **{total_classes} classes** "
        f"were extracted and semantically indexed."
    )
    if explained:
        summary += (
            f" **{explained} file(s)** received detailed explanations "
            f"from the LLM analysis."
        )
    lines.append(summary)

    # Risk and dependency health.
    # health collects only the BAD signals (things to flag with attention).
    # Circular dep cleanliness is always stated explicitly — it must appear
    # in the output whether cycles exist or not. The test for the clean case
    # checks for "no circular" or "not detected" in the output, so we cannot
    # rely on the else-branch alone (which only fires when health is empty).
    risk_dist = _compute_risk_distribution(state)
    critical  = risk_dist.get("CRITICAL", 0)
    high      = risk_dist.get("HIGH", 0)
    health    = []

    if critical:
        health.append(f"**{critical} CRITICAL** risk file(s)")
    if high:
        health.append(f"**{high} HIGH** risk file(s)")
    if state.circular_deps:
        health.append(
            f"**{len(state.circular_deps)} circular dependency cycle(s)**"
        )

    if health:
        lines.append(
            "\n**Attention required:** " + ", ".join(health) + " identified."
        )
        # FIX: when other risks exist but NO circular deps, we must still
        # say so explicitly. Without this line the clean-cycles case produces
        # output that mentions CRITICAL/HIGH but says nothing about circular
        # deps — the test asserts "no circular" or "not detected" must appear.
        if not state.circular_deps:
            lines.append("No circular dependencies detected.")
    else:
        lines.append(
            "\nNo critical risks or circular dependencies were detected."
        )

    return '\n'.join(lines)


def _get_summary_opening(state: ArchaeonState) -> str:
    """
    Find the most structurally central file that has an explanation,
    and extract its first two sentences as a summary opener.

    WHY THE MOST-IMPORTED FILE:
    The file imported by the most other files is the closest thing to
    a "topic sentence" for the codebase. It defines the concepts or
    interfaces that everything else builds on. Its explanation describes
    what the repo fundamentally does.
    """
    if not state.explanations or not state.graph_stats:
        # Fall back to module docstrings of shallow files
        for path, st in state.symbol_tables.items():
            if path.count('/') <= 1 and st.module_docstring:
                return f"*{st.module_docstring.strip()}*"
        return ""

    best_path     = None
    best_indegree = -1
    for path in state.explanations:
        indegree = state.graph_stats.get(path, {}).get('in_degree', 0)
        if indegree > best_indegree:
            best_indegree = indegree
            best_path     = path

    if not best_path:
        return ""

    explanation = state.explanations[best_path]
    # Split on '. ' to get sentences; take first two
    raw     = explanation.replace('\n', ' ').strip()
    parts   = raw.split('. ')
    excerpt = '. '.join(parts[:2]).strip()
    if excerpt and not excerpt.endswith('.'):
        excerpt += '.'

    return f"*{excerpt}*" if excerpt else ""


