def _ac_critical_entry_points(state: ArchaeonState) -> str:
    lines = ["## Critical Entry Points", ""]

    if state.dependency_graph is None:
        lines += ["*Dependency graph not available.*", ""]
        return "\n".join(lines) + "\n"

    in_deg = dict(state.dependency_graph.in_degree())
    out_deg = dict(state.dependency_graph.out_degree())

    entry_points = [
        fp for fp, ind in in_deg.items()
        if ind == 0 and out_deg.get(fp, 0) > 0
    ]
    entry_points.sort(key=lambda fp: out_deg.get(fp, 0), reverse=True)

    if not entry_points and state.topological_order:
        entry_points = [fp for fp in state.topological_order if in_deg.get(fp, 0) == 0][:5]

    if not entry_points:
        all_nodes = sorted(out_deg.items(), key=lambda x: x[1], reverse=True)
        entry_points = [fp for fp, d in all_nodes if d > 0][:5]

    if not entry_points:
        lines += ["*No entry points identified. All files may be in cycles.*", ""]
        return "\n".join(lines) + "\n"

    lines.append("Files not imported by any other file. Execution likely begins here.")
    lines.append("")

    for fp in entry_points[:10]:
        short = _short_path(fp)
        out = out_deg.get(fp, 0)
        cs = state.complexity_scores.get(fp)
        risk_tag = f" · risk: {getattr(cs, 'risk_level', '?')}" if cs else ""
        lines.append(f"- `{short}` — imports {out} module(s){risk_tag}")

    lines.append("")
    return "\n".join(lines) + "\n"


