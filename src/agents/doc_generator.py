# -----------------------------------------------------------------------

def _build_reading_order(state: ArchaeonState) -> str:
    lines = ["## Suggested Reading Order\n"]

    if state.topological_order:
        # We have a clean order (no cycles)
        display_paths = state.topological_order[:READING_ORDER_CAP]

        lines.append(
            "Read these files in order. Each file appears after everything "
            "it depends on, so you build understanding incrementally "
            "without forward-referencing concepts you have not seen yet.\n"
        )

        for i, path in enumerate(display_paths, start=1):
            name    = PurePosixPath(path).name
            score   = state.complexity_scores.get(path)
            risk    = score.risk_level if score else ""
            in_deg  = state.graph_stats.get(path, {}).get('in_degree', 0)

            annotation_parts = []
            if in_deg >= 5:
                annotation_parts.append(f"imported by {in_deg} files")
            if risk in ("HIGH", "CRITICAL"):
                annotation_parts.append(f"{risk} risk — read carefully")

            annotation = f" — *{', '.join(annotation_parts)}*" if annotation_parts else ""
            lines.append(f"{i:>2}. `{path}`{annotation}")

        total = len(state.topological_order)
        if total > READING_ORDER_CAP:
            lines.append(
                f"\n*...and {total - READING_ORDER_CAP} more files. "
                f"Full order available in `graph_data.json` → `topological_order`.*"
            )
    else:
        # Cycles exist — explain why and show what we can
        lines.append(
            "⚠️ **A complete reading order cannot be computed** because "
            "circular dependencies exist in this codebase. Files involved "
            "in cycles have no well-defined reading order — each requires "
            "understanding the other first.\n"
        )

        if state.circular_nodes:
            cycle_names = [
                PurePosixPath(p).name for p in list(state.circular_nodes)[:6]
            ]
            lines.append(
                f"**Files in cycles:** "
                f"{', '.join(f'`{n}`' for n in cycle_names)}"
            )
            if len(state.circular_nodes) > 6:
                lines.append(f" +{len(state.circular_nodes) - 6} more")
            lines.append("")

        lines.append(
            "**Recommended first steps:**\n\n"
            "1. Resolve the circular dependencies in the Tech Debt Report above.\n"
            "2. Re-run Project Gnosis to get a complete reading order.\n"
            "3. In the meantime, start with low in-degree, low-risk files "
            "and work outward.\n"
        )

        # Show safest files to start with regardless
        safe_files = [
            (path, state.graph_stats.get(path, {}).get('in_degree', 0))
            for path, score in state.complexity_scores.items()
            if score.risk_level == "LOW"
            and path not in state.circular_nodes
        ]
        safe_files.sort(key=lambda x: -x[1])
        if safe_files:
            lines.append(
                "**Suggested starting points (LOW risk, not in cycles):**\n"
            )
            for path, in_deg in safe_files[:8]:
                lines.append(f"- `{path}` (imported by {in_deg} files)")

    return '\n'.join(lines)


