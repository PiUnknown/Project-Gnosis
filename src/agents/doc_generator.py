def generate_agent_context_doc(state: ArchaeonState) -> str:
    """
    Assemble agent_context.md from all _ac_* section generators.
    Concise by design — tables and bullets, not prose.
    Target use: paste as system context before asking an LLM to edit this repo.
    Every section is independently try/except wrapped.
    """
    repo = _repo_name(state)
    now = _timestamp()

    header = (
        f"# Repository Agent Context: `{repo}`\n\n"
        f"*Generated by Project Gnosis · {now} · {state.analysis_mode} mode*  \n"
        f"*Source: {state.repo_url} · Branch: {_default_branch(state)}*\n\n"
        f"> This document is optimised for AI coding agents.\n"
        f"> For human-readable documentation see `onboarding.md`.\n\n"
        f"---\n\n"
    )

    sections = [
        ("System Overview",             _ac_system_overview),
        ("Critical Entry Points",       _ac_critical_entry_points),
        ("Core Components",             _ac_core_components),
        ("Architectural Relationships", _ac_architectural_relationships),
        ("High Risk Areas",             _ac_high_risk_areas),
        ("Circular Dependencies",       _ac_circular_dependencies),
        ("Important Domain Objects",    _ac_important_domain_objects),
        ("Change Impact Guide",         _ac_change_impact_guide),
        ("Safe Starting Points",        _ac_safe_starting_points),
        ("AI Explanations",             _ac_ai_explanations),
    ]

    parts = [header]
    for name, fn in sections:
        try:
            parts.append(fn(state))
        except Exception as exc:
            logger.warning("agent_context.md: section '%s' failed: %s", name, exc)
            parts.append(f"## {name}\n\n*Section unavailable.*\n\n")

    parts.append(f"---\n\n*Project Gnosis · Code Archaeology Agent · {now}*\n")
    return "".join(parts)


