"""
Agent 7: Doc Generator Agent

Synthesises all pipeline outputs into:
  - state.final_doc          → onboarding.md  (human-oriented)
  - state.agent_context_md   → agent_context.md (AI coding agent-oriented)
  - state.complexity_report_json → complexity_report.json

Design invariants:
  - Zero new analysis. All data sourced from ArchaeonState as-is.
  - Every section generator is independently wrapped in try/except.
    One section failing never prevents the rest from rendering.
  - agent_context.md is concise by design: tables and bullets, not prose.
    Target audience is an LLM's system prompt, not a human reader.
"""

