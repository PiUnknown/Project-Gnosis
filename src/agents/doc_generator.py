def run(state: ArchaeonState) -> ArchaeonState:
    """
    Agent 7: Doc Generator.
    Called as doc_generator.run(state) by pipeline_runner.py.

    Writes three fields to state:
      state.final_doc              — onboarding.md content
      state.agent_context_md       — agent_context.md content
      state.complexity_report_json — complexity data as JSON string
    """
    logger.info("Doc Generator Agent: starting")

    # ── onboarding.md ────────────────────────────────────────────────────
    onboarding_sections = [
        _build_header,
        _build_project_summary,
        _build_repository_statistics,
        _build_architecture_map,
        _build_core_components,
        _build_tech_debt_report,
        _build_reading_order,
        _build_footer,
    ]
    parts = []
    for fn in onboarding_sections:
        try:
            parts.append(fn(state))
        except Exception as exc:
            logger.warning("onboarding.md: section '%s' failed: %s", fn.__name__, exc)

    state.final_doc = "".join(parts)
    logger.info("Doc Generator: onboarding.md complete (%d chars)", len(state.final_doc))

    # ── agent_context.md ─────────────────────────────────────────────────
    try:
        state.agent_context_md = generate_agent_context_doc(state)
        logger.info(
            "Doc Generator: agent_context.md complete (%d chars)",
            len(state.agent_context_md),
        )
    except Exception as exc:
        logger.error("Doc Generator: agent_context.md failed: %s", exc)
        state.agent_context_md = f"# Repository Agent Context\n\n*Generation failed: {exc}*\n"

    # ── complexity_report_json ────────────────────────────────────────────
    try:
        state.complexity_report_json = generate_complexity_report_json(state)
        logger.info("Doc Generator: complexity_report.json complete")
    except Exception as exc:
        logger.error("Doc Generator: complexity report failed: %s", exc)
        state.complexity_report_json = "{}"

    return state