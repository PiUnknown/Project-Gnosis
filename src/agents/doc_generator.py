# Section 4: Architecture Map
# -----------------------------------------------------------------------

def _build_architecture_map(state: ArchaeonState) -> str:
    if not state.graph_stats:
        return ""

    # Sort by in-degree descending, take top N
    ranked = sorted(
        state.graph_stats.items(),
        key=lambda x: (-x[1]['in_degree'], x[0])
    )
    # Only show files that are actually imported by something
    ranked = [(p, s) for p, s in ranked if s['in_degree'] > 0][:ARCH_MAP_CAP]

    if not ranked:
        return (
            "## Architecture Map\n\n"
            "*No internal import relationships detected. "
            "Files may be standalone scripts or the import resolution "
            "found no internal connections.*"
        )

    max_indegree = max(s['in_degree'] for _, s in ranked) or 1

    lines = ["## Architecture Map\n"]
    lines.append(
        "Files ranked by how many other files import them. "
        "Higher in-degree means changing this file has wider impact.\n"
    )
    lines.append("```")
    lines.append(
        f"{'FILE':<45} {'IMPORTS':>7}  {'RISK':<8}"
    )
    lines.append("─" * 65)

    for path, stats in ranked:
        in_deg   = stats['in_degree']
        risk     = state.complexity_scores.get(path)
        risk_lvl = risk.risk_level if risk else "—"
        is_circ  = path in state.circular_nodes

        bar_len  = round((in_deg / max_indegree) * 20)
        bar      = "█" * bar_len + "░" * (20 - bar_len)
        name     = PurePosixPath(path).name
        circ_tag = " ⚠" if is_circ else ""

        lines.append(
            f"  {bar}  {name:<35}{circ_tag:2}  {in_deg:>4}    {risk_lvl}"
        )

    lines.append("```")

    isolated = sum(
        1 for p, s in state.graph_stats.items()
        if s['in_degree'] == 0 and s['out_degree'] == 0
    )
    if isolated:
        lines.append(
            f"\n*{isolated} file(s) have no import relationships "
            f"(isolated scripts or entry points).*"
        )
    if state.circular_nodes:
        lines.append(
            f"\n*⚠ = file is part of a circular dependency cycle.*"
        )

    return '\n'.join(lines)


