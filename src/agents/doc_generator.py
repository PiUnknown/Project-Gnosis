# -----------------------------------------------------------------------

def _build_core_components(state: ArchaeonState) -> str:
    if not state.explanations:
        return (
            "## Core Components\n\n"
            "*No LLM explanations available. "
            "Run Phase 6 with a valid GROQ_API_KEY to generate explanations.*"
        )

    # Sort explained files by in-degree descending
    sorted_paths = sorted(
        state.explanations.keys(),
        key=lambda p: -state.graph_stats.get(p, {}).get('in_degree', 0)
    )[:COMPONENT_CAP]

    lines = ["## Core Components\n"]
    lines.append(
        f"*{len(sorted_paths)} file(s) with LLM-generated explanations, "
        f"ordered by structural importance (in-degree).*\n"
    )

    for path in sorted_paths:
        explanation = state.explanations[path]
        score       = state.complexity_scores.get(path)
        stats       = state.graph_stats.get(path, {})
        language    = score.language if score else "Unknown"
        risk_lvl    = score.risk_level if score else "—"
        in_degree   = stats.get('in_degree', 0)

        # Heading: full path as inline code
        lines.append(f"### `{path}`\n")

        # Badges row
        badge_parts = [
            f"**Language:** {language}",
            f"**Risk:** {risk_lvl}",
            f"**Imported by:** {in_degree} file(s)",
        ]
        if score and score.function_count:
            badge_parts.append(f"**Functions:** {score.function_count}")
        if score and score.avg_complexity > 0:
            badge_parts.append(
                f"**Avg complexity:** {score.avg_complexity:.1f}"
            )
        lines.append(' · '.join(badge_parts) + "\n")

        # Explanation
        lines.append(explanation.strip() + "\n")

        # Dependency context as a blockquote
        dep_lines = []
        dependencies = stats.get('dependencies', [])
        dependents   = stats.get('dependents',   [])

        if dependencies:
            dep_names = [PurePosixPath(d).name for d in dependencies[:MAX_RELATED]]
            extra = len(dependencies) - MAX_RELATED
            dep_str = ', '.join(f"`{n}`" for n in dep_names)
            if extra > 0:
                dep_str += f" +{extra} more"
            dep_lines.append(f"**Imports:** {dep_str}")
        else:
            dep_lines.append("**Imports:** nothing internal")

        if dependents:
            dep_names = [PurePosixPath(d).name for d in dependents[:MAX_RELATED]]
            extra = len(dependents) - MAX_RELATED
            dep_str = ', '.join(f"`{n}`" for n in dep_names)
            if extra > 0:
                dep_str += f" +{extra} more"
            dep_lines.append(f"**Imported by:** {dep_str}")

        if dep_lines:
            lines.append('> ' + '  \n> '.join(dep_lines) + "\n")

    return '\n'.join(lines)


